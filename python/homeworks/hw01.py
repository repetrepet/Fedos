# 2. Вывести все математические операции между числами 23 и 5 (сложение, умножение, и т.д.)

# В исходном решении используется число 22; сохраняем его без изменений.
print(22 + 5)   # сложение
print(22 - 5)   # вычитание
print(22 * 5)   # умножение
print(22 / 5)   # деление
print(22 // 5)  # сколько пятёрок влезет в 22?
print(22 % 5)   # 5 + 5 + 5 + 5 = 20; остаток: 22 - 20 = 2
print(22 ** 5)  # возведение в степень: 22 * 22 * 22 * 22 * 22


