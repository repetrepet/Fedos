# Тема: булев тип данных, сравнения и условный оператор if/else.

# =============================================================================
# Типы данных и сравнения
# =============================================================================

# int — целое число (1, 2, 3, 4, 5 ...).
# str — строка ('a', 'b', 'c' ...).
# bool — булев тип данных: True (истина) или False (ложь).

# Операции сравнения возвращают значение типа bool.
a = 10
print(a > 5)     # больше
print(a < 5)     # меньше
print(a >= 100)  # больше или равно
print(a <= 100)  # меньше или равно
print(a == 10)   # равно: для сравнения используются два знака =
print(a != 10)   # не равно

# Примеры результатов сравнения.
print(5 > 3)   # True
print(7 == 8)  # False
print(10 != 4) # True
print(6 <= 6)  # True


# =============================================================================
# Условный оператор if/else
# =============================================================================

# if выполняет свой блок, если условие истинно (True).
# else выполняет свой блок, если условие if ложно (False).
# Отступы определяют, какие строки относятся к каждому блоку.
age = 10
if age >= 18:
    print('Совершеннолетний')
    print('Проходите')
else:
    print('Несовершеннолетний')


# =============================================================================
# Определить число положительное или нет
# =============================================================================

# Сравниваем число с нулём и выбираем соответствующий блок.
n = -10
if n > 0:
    print("положительное")
else:
    print("отрицательное")


# =============================================================================
# Определить число чётное или нет
# =============================================================================

# Важно запомнить: у чётного числа остаток от деления на 2 равен нулю.
n = 4
if n % 2 == 0:
    print('Четное')
else:
    print('Нечетное')


# =============================================================================
# Вывести наибольшее число
# =============================================================================

# Сравниваем два числа и выводим число из выбранного блока.
a = 105
b = 466
if a > b:
    print(a)
else:
    print(b)


# Занятие 14.10.2026
# Тема: elif и логические операторы and, or, not.

# =============================================================================
# Определить число положительное или нет: вариант с elif
# =============================================================================

# elif проверяет дополнительное условие, если условие if ложно.
# Отдельно рассматриваем положительное число, ноль и отрицательное число.
x = 7
if x > 0:
    print("положительное")
elif x == 0:
    print('X = 0')
else:
    print("отрицательное")


# =============================================================================
# Проверить что х находится в диапазоне от 0 до 100
# =============================================================================

# and требует, чтобы оба условия были истинны одновременно.
x = 105
if x > 0 and x < 100:
    print('Да, находится')
else:
    print("Нет, не находится")

# or даёт истину, если истинно хотя бы одно из условий.
if x < 0 or x > 100:
    print('Нет, не находится')
else:
    print('находится')

# not меняет логическое значение на противоположное.
print(not(False))


# =============================================================================
# Проверить что число положительное и четное
# =============================================================================

# Проверяем одновременно знак числа и остаток от деления на 2.
x = 11
if (x > 0) and (x % 2 == 0):
    print("подходит")
else:
    print("не подходит")
