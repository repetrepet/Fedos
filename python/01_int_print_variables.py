# =============================================================================
# Вывод данных и арифметические операции
# =============================================================================

# Функция print() выводит текст или результат выражения.
print("Привет мир!")

# Основные арифметические операции с числами.
print(5 + 3)   # сложение
print(5 - 3)   # вычитание
print(5 * 3)   # умножение
print(5 / 3)   # деление
print(5 // 3)  # целая часть от деления
print(5 % 3)   # остаток от деления
print(5 ** 3)  # возведение в степень

# Числа складываются, а строки соединяются.
print(5 + 3)
print('5' + '3')


# =============================================================================
# Переменные
# =============================================================================

# В переменных можно хранить числа и строки, затем передавать их в print().
number = 10
string = 'Hello!'
print(string, number)

# Переменной можно присвоить новое значение другого типа.
number = 10
print(number)
number = 'Hello'
print(number)


# =============================================================================
# Работа с цифрами числа
# =============================================================================

# Остаток от деления на 10 даёт последнюю цифру целого числа.
# Целочисленное деление на 10 отбрасывает последнюю цифру.
x = 1232389652897639
print(x % 10)   # последняя цифра числа
print(x // 10)  # все цифры, кроме последней

# Дано двузначное число 47. Найти сумму его цифр.
x = 47
a = x % 10   # последняя цифра: 7
b = x // 10  # первая цифра: 4
print(a + b)  # сумма цифр

# Для чисел a = 15 и b = 4 найдём сумму, произведение и остаток от деления.
a = 15
b = 4
print(a + b)  # сумма чисел
print(a * b)  # произведение чисел
print(a % b)  # остаток от деления a на b

# Для трёхзначного числа n можно выделить каждую цифру отдельно.
n = 234
print(n % 10)           # последняя цифра
print(n // 100)         # первая цифра
print((n % 100) // 10)  # средняя цифра

# Вывести сумму цифр числа n: сначала выделим последнюю, первую и среднюю.
a = n % 10
b = n // 100
c = (n % 100) // 10
print(a + b + c)
